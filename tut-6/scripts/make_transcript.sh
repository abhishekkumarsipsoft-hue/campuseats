#!/usr/bin/env bash
# Regenerates transcript.txt: starts the Orders service (+ a Payments stub)
# several times with different settings, drives every success and failure
# path with curl -i, and kills everything again.
#
#   cd assignment6 && bash scripts/make_transcript.sh            (Linux/macOS/Git Bash)
#   PYTHON=python bash scripts/make_transcript.sh                 (if your interpreter is `python`)
#
# Needs: bash, curl, python with `pip install -r requirements.txt`.
set -u
cd "$(dirname "$0")/.."
PY=${PYTHON:-python3}
OUT=transcript.txt
TMP=$(mktemp)
PIDS=()
trap 'kill "${PIDS[@]}" 2>/dev/null' EXIT

start() { # start <label> <env assignments...> -- <script>
  local env=() ; while [ "$1" != "--" ]; do env+=("$1"); shift; done; shift
  env "${env[@]}" "$PY" "$1" >/dev/null 2>&1 & PIDS+=($!)
}
wait_up() { for _ in $(seq 1 50); do curl -s -o /dev/null "http://localhost:$1/orders" && return; sleep 0.2; done; echo "port $1 never came up" >&2; exit 1; }

# 8000 main | 8002 Payments declines | 8003 Payments is down | 8004 tiny rate limit
start STUB_PORT=9001 STUB_MODE=ok       -- payments_stub.py
start STUB_PORT=9002 STUB_MODE=decline  -- payments_stub.py
start PORT=8000 PAYMENTS_SERVICE_URL=http://localhost:9001 -- app.py
start PORT=8002 PAYMENTS_SERVICE_URL=http://localhost:9002 -- app.py
start PORT=8003 PAYMENTS_SERVICE_URL=http://localhost:9999 -- app.py
start PORT=8004 RATE_LIMIT=3 RATE_WINDOW_S=60 PAYMENTS_SERVICE_URL=http://localhost:9001 -- app.py
for p in 8000 8002 8003 8004; do wait_up $p; done

B=http://localhost:8000
TOKEN="Authorization: Bearer test-token-123"
JSON="Content-Type: application/json"
LAST=""

banner() { printf '\n############################################\n# %s\n############################################\n' "$1"; }

# req <note> <curl args...>   - prints the command, then the raw response (curl -i)
show_cmd() { # print args the way you would type them: quote only when needed
  printf '$ curl -i'
  local a; for a in "$@"; do
    if [[ $a =~ ^[A-Za-z0-9_./:=@%+,-]+$ ]]; then printf ' %s' "$a"; else printf " '%s'" "$a"; fi
  done; printf '\n'
}
req() {
  local note=$1; shift
  printf '\n# %s\n' "$note"; show_cmd "$@"; printf '\n'
  curl -i -s "$@" > "$TMP"
  tr -d '\r' < "$TMP" | grep -v -i -E '^(access-control-|strict-transport-security|x-content-type-options)'
  echo
  LAST=$(tr -d '\r' < "$TMP" | grep -i '^location:' | awk '{print $2}')
}

{
echo "CS543 Assignment 6 - Orders service - curl transcript"
echo "Team members: Binamra Rana (20251651033), Abhishek Kumar (20251651005),"
echo "              Navendu Kumar Pandey (20251651062), Yatindra Kumar Yunish (20251651106),"
echo "              Shruti Singh (20251651087)"
echo "Generated by scripts/make_transcript.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
echo "Every response is raw 'curl -i' output. To keep it readable, three constant headers"
echo "(Access-Control-*, Strict-Transport-Security, X-Content-Type-Options) are filtered out;"
echo "they are identical on every response and unchanged since A5."

banner "D1  SUCCESS PATH"
req "1. Create an order -> 201 Created + Location" -X POST $B/orders -H "$JSON" -H "$TOKEN" -H "Idempotency-Key: key-abc-1" \
  -d '{"customer_id":"student-42","address":"Hostel B, Room 214","items":[{"name":"Masala Dosa","price_cents":8000,"qty":2},{"name":"Filter Coffee","price_cents":3000,"qty":1}]}'
ORDER=$LAST
req "2. Follow the Location header -> 200 OK + ETag" $B$ORDER
req "3. List with a filter -> 200 OK" "$B/orders?status=placed"
req "4. PATCH the order forward: placed -> preparing -> 200 OK" -X PATCH $B$ORDER -H "$JSON" -H "$TOKEN" -d '{"status":"preparing"}'

banner "D2  FAILURE PATHS (status + Problem Details body)"
req "5. Empty cart -> 422 empty-cart, errors[] names the field" -X POST $B/orders -H "$JSON" -H "$TOKEN" \
  -d '{"customer_id":"student-42","address":"Hostel B","items":[]}'
req "6. qty <= 0 AND address missing -> ONE 422 listing BOTH bad fields" -X POST $B/orders -H "$JSON" -H "$TOKEN" \
  -d '{"customer_id":"student-42","items":[{"name":"Masala Dosa","price_cents":8000,"qty":0}]}'
req "7. Item no longer available -> 422 item-unavailable" -X POST $B/orders -H "$JSON" -H "$TOKEN" \
  -d '{"customer_id":"student-42","address":"Hostel B","items":[{"name":"Sold-Out Samosa","price_cents":500,"qty":1}]}'
req "8. Unknown id -> 404 order-not-found" $B/orders/does-not-exist-id
req "9. Illegal transition: PATCH preparing -> delivered (skips a step) -> 409 illegal-transition" \
  -X PATCH $B$ORDER -H "$JSON" -H "$TOKEN" -d '{"status":"delivered"}'
req "10a. (setup) move the order to out_for_delivery" -X PATCH $B$ORDER -H "$JSON" -H "$TOKEN" -d '{"status":"out_for_delivery"}'
req "10b. Illegal transition: cancel an order that is already out for delivery -> 409 illegal-transition" \
  -X DELETE $B$ORDER -H "$TOKEN"
req "11. Malformed JSON -> 400 malformed-json" -X POST $B/orders -H "$JSON" -H "$TOKEN" -d '{"customer_id": '
req "12. No Bearer token -> 401 unauthorized" -X POST $B/orders -H "$JSON" \
  -d '{"customer_id":"s","address":"a","items":[{"name":"Idli","price_cents":3000,"qty":1}]}'
req "13. Unknown URL -> 404 not-found, still Problem Details (not Flask's HTML page)" $B/no/such/thing
req "14. Wrong method -> 405 method-not-allowed (+ Allow)" -X PUT $B$ORDER -H "$TOKEN"
req "15. Client wants HTML -> 406 not-acceptable" $B/orders -H "Accept: text/html"

req "16. Payments declines the refund -> 402 payment-declined (port 8002 talks to a declining stub)" \
  -X POST http://localhost:8002/orders -H "$JSON" -H "$TOKEN" \
  -d '{"customer_id":"student-42","address":"Hostel B","items":[{"name":"Idli","price_cents":3000,"qty":1}]}'
DECL=$LAST
req "16b. ...cancel it" -X DELETE http://localhost:8002$DECL -H "$TOKEN"
req "16c. ...and the order was NOT cancelled (still 'placed')" http://localhost:8002$DECL

req "17. (setup) order on the instance whose Payments service is down" \
  -X POST http://localhost:8003/orders -H "$JSON" -H "$TOKEN" \
  -d '{"customer_id":"student-42","address":"Hostel B","items":[{"name":"Idli","price_cents":3000,"qty":1}]}'
DOWN=$LAST
req "17b. Cancel while Payments is unreachable -> 503 payments-unavailable + Retry-After (after 4 timed-out attempts with backoff)" \
  -X DELETE http://localhost:8003$DOWN -H "$TOKEN" -w '\n[curl total time: %{time_total}s]\n'
req "17c. ...order is back to 'placed', not stuck in 'cancelling'" http://localhost:8003$DOWN

for i in 1 2 3; do curl -s -o /dev/null http://localhost:8004/orders; done
req "18. Rate limit (this instance allows 3/min; the 4th call) -> 429 rate-limit-exceeded + Retry-After" http://localhost:8004/orders

banner "D3  CONTENT NEGOTIATION"
req "19. Same order as XML -> 200, Content-Type: application/xml" $B$ORDER -H "Accept: application/xml"
req "20. Same order as JSON (default, no Accept header)" $B$ORDER
req "21. Quality values: prefers XML (q=0.9) over JSON (q=0.5) -> XML" $B/orders -H "Accept: application/json;q=0.5, application/xml;q=0.9"

banner "D4  NO REGRESSIONS (A5 behaviour still holds)"
req "22a. Idempotency: first create with a new key -> 201" -X POST $B/orders -H "$JSON" -H "$TOKEN" -H "Idempotency-Key: key-regress-1" \
  -d '{"customer_id":"student-7","address":"Library","items":[{"name":"Idli","price_cents":3000,"qty":1}]}'
R1=$LAST
req "22b. Same key + same body -> original order again (same id, same Location, no duplicate)" -X POST $B/orders -H "$JSON" -H "$TOKEN" -H "Idempotency-Key: key-regress-1" \
  -d '{"customer_id":"student-7","address":"Library","items":[{"name":"Idli","price_cents":3000,"qty":1}]}'
ETAG=$(curl -s -i $B$R1 | tr -d '\r' | grep -i '^etag:' | cut -d' ' -f2-)
req "23a. Conditional GET with the current ETag -> 304, empty body" $B$R1 -H "If-None-Match: $ETAG"
req "23b. Conditional write with a stale ETag -> 412 precondition-failed" -X POST $B$R1/cancellation -H "$JSON" -H "$TOKEN" -H 'If-Match: W/"stale"' -d '{}'
req "24. Cancel via the sub-resource: refund succeeds against the Payments stub -> 202" -X POST $B$R1/cancellation -H "$JSON" -H "$TOKEN" -d '{"reason":"Changed my mind"}'
req "25. Cancel again -> 409 illegal-transition (no second refund)" -X POST $B$R1/cancellation -H "$JSON" -H "$TOKEN" -d '{}'
printf '\n# 26. Timeouts / retries (A5 D1/D2): shown in 17b above - 4 attempts with exponential backoff\n#     and jitter (about 2 s in total), then a clean 503 with Retry-After instead of a hang.\n'
} > "$OUT" 2>&1
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
